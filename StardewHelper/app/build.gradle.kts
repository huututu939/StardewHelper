// 把 `*` 与 `**` 通配转成正则字符串，语义对齐 Gradle 的 include 模式：
// `**` 跨任意层目录，`**` 后面跟斜杠时还可匹配零层目录，其余字符按字面量转义。
// ⚠ 这里刻意用行注释而非 KDoc：文档里要举 `**` 加斜杠这个例子，而它字面上就含
// 「星号紧跟斜杠」，写进块注释会当场把注释闭合掉，后面整段被当代码解析（已踩过一次）。
// 另：刻意返回 String 而不是 Regex —— doLast 里用 java.util.regex.Pattern.matches 消费，
// 这样闭包在配置缓存下只捕获 List<String>，不会去序列化 Regex。
fun devAssetGlobToRegex(glob: String): String {
    val sb = StringBuilder()
    var i = 0
    while (i < glob.length) {
        val c = glob[i]
        when {
            c == '*' && i + 1 < glob.length && glob[i + 1] == '*' -> {
                sb.append(".*")
                i++
                if (i + 1 < glob.length && glob[i + 1] == '/') i++
            }
            c == '*' -> sb.append("[^/]*")
            c == '/' -> sb.append('/')
            else -> sb.append(Pattern.quote(c.toString()))
        }
        i++
    }
    return sb.toString()
}

