# -*- coding: utf-8 -*-
"""从 send_save.ps1 生成**单文件自包含**的 send_save.bat。

为什么要有这个生成器（2026-10-16 群友实测反馈驱动）：
    上一版分发的是 bat + ps1 两个文件，bat 用 `-File send_save.ps1` 调旁边的脚本。
    群友从 QQ 群只下载了 bat 没下 ps1，双击后得到一屏
    「-File 形式参数的实际参数 …send_save.ps1 不存在」——错误本身没错，
    但**指望普通用户把两个文件放同一个目录**就是设计缺陷，不是用户失误。

    所以 bat 改成自包含：ps1 的 UTF-8(带 BOM) 字节做 base64，按行嵌进 bat，
    运行时写进 %TEMP%，用 Windows 自带的 certutil -decode 还原成 ps1 再执行。
    群友只需要一个文件。

三条硬约束（都有实测依据，verify 58.26 钉住）：
    ① bat 必须**纯 ASCII**——cmd 按系统 OEM 代码页（中文 Windows=GBK）读 bat，
       UTF-8 中文会被拆成乱码命令执行。base64 字母表恰好全是 ASCII。
    ② 每行 < 4000 字符——cmd 单行上限 8191，`echo <行>` 同样受限，留一倍余量。
    ③ 内嵌的 ps1 字节必须**带 UTF-8 BOM**——PowerShell 5.1 读无 BOM 的 UTF-8
       会按 ANSI 解，中文提示全乱码。

用法（在 StardewHelper/ 下）：
    python tools/gen_send_save_bat.py            # 生成
    python tools/gen_send_save_bat.py --check    # 只校验磁盘上的 bat 与生成结果一致
"""
import base64
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PS1 = os.path.join(HERE, "send_save.ps1")
BAT = os.path.join(HERE, "send_save.bat")
LINE_LEN = 4000

HEADER = """@echo off
rem ============================================================
rem  StardewHelper - send your Stardew Valley save to your phone
rem  SINGLE FILE: this .bat carries the PowerShell inside it
rem  (base64, decoded at runtime with certutil). Download ONLY
rem  this file - nothing else is needed. No Python, no install.
rem
rem  Before running:
rem    1. Phone and PC must be on the SAME WiFi.
rem    2. On the phone open: Settings > Import game save >
rem       Receive from PC > Start receiving (shows the address:
rem       IP and port, e.g. 192.168.1.7:54321).
rem    3. A 6-digit code shows up here - type it on the phone.
rem
rem  Generated by tools/gen_send_save_bat.py - DO NOT EDIT by
rem  hand; edit send_save.ps1 and regenerate.
rem ============================================================
setlocal
set "B64=%TEMP%\\sdh_%RANDOM%.b64"
set "PS1=%TEMP%\\sdh_%RANDOM%.ps1"
"""

FOOTER = """certutil -f -decode "%B64%" "%PS1%" >nul 2>nul
if errorlevel 1 (
    echo [X] failed to unpack the embedded script - temp dir not writable?
    pause & endlocal & exit /b 1
)
powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%PS1%" %*
set "RC=%ERRORLEVEL%"
del "%B64%" "%PS1%" >nul 2>nul
echo.
if "%RC%"=="0" (
    echo Done. You can close this window now.
) else (
    echo Failed. Please read the text above, or ask in the QQ group.
)
pause
endlocal
exit /b %RC%
"""


def build():
    # 读 ps1 的原始字节（必须带 BOM，下面断言），base64 后按行嵌入
    raw = open(PS1, "rb").read()
    if raw[:3] != b"\xef\xbb\xbf":
        raise SystemExit("✗ send_save.ps1 没有 UTF-8 BOM——PS 5.1 会把中文解成乱码，"
                         "先给 ps1 补 BOM 再生成")
    b64 = base64.b64encode(raw).decode("ascii")
    # ⚠ 重定向必须放**行首**（`>>"file" echo <内容>`）：若写成 `echo <内容>>>file`，
    #   而 base64 行恰好以数字结尾，cmd 会把 `5>>` 解析成句柄 5 重定向——
    #   实测报「命令语法不正确」，第一行就炸。行首重定向让内容与 `>` 永不相邻。
    lines = [">>\"%%B64%%\" echo %s" % b64[i:i + LINE_LEN]
             for i in range(0, len(b64), LINE_LEN)]
    return HEADER + "\r\n".join(lines) + "\r\n" + FOOTER


def to_bytes(blob):
    """把 blob 统一成**纯 CRLF 的 ASCII 字节**——即真正落盘的形态。

    ⚠ 为什么必须比字节、不能直接比字符串（v2.68.0 实测修的真 bug）：
        HEADER/FOOTER 是 Python 三引号串（行尾 LF），中间 base64 行是用
        "\\r\\n".join 拼的（行尾 CRLF），所以 `blob` 本身就是**混着行尾**的；
        而落盘时会统一转成 CRLF。初版 `--check` 拿「落盘后的 CRLF 文本」
        去比「混行尾的 blob」，于是**永远不相等**——一条从来没绿过的守卫，
        等于没有守卫：改了 ps1 忘重跑生成器也不会红，而它自己一直喊红，
        结果没人当真。比较基准必须与比较对象的形态一致。
    """
    return blob.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii")


def main():
    check_only = "--check" in sys.argv
    blob = build()
    # 自校验：纯 ASCII + 单行长度
    bad = [i for i, ln in enumerate(blob.splitlines(), 1)
           if any(ord(ch) > 127 for ch in ln)]
    if bad:
        raise SystemExit("✗ 生成的 bat 第 %s 行含非 ASCII 字符" % bad[:3])
    toolong = [i for i, ln in enumerate(blob.splitlines(), 1) if len(ln) > 8000]
    if toolong:
        raise SystemExit("✗ 生成的 bat 第 %s 行超过 cmd 单行上限" % toolong[:3])
    if check_only:
        if not os.path.exists(BAT):
            raise SystemExit("✗ send_save.bat 不存在")
        cur = open(BAT, "rb").read()
        want = to_bytes(blob)
        if cur != want:
            print("磁盘上的 bat 与重新生成的不一致，请重跑（不带 --check）")
            return 1
        print("--check 通过：bat 与 ps1 内嵌内容逐字节一致（%d 字节）" % len(cur))
        return 0
    with io.open(BAT, "wb") as f:
        f.write(to_bytes(blob))
    print("已生成 %s（%d 字节，内嵌 ps1 %d 字节）" % (BAT, len(blob), os.path.getsize(PS1)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
