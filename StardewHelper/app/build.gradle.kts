tasks.matching { it.name.startsWith("merge") && it.name.endsWith("Assets") }.configureEach {
    // 下面会在 doLast 里删掉本任务自己声明的输出，因此必须禁掉构建缓存：
    // 一旦命中缓存，actions 压根不跑，被剔掉的开发产物会原样回到 APK。
    outputs.cacheIf { false }
    doLast {
        val dirs = outputs.files.files.filter { it.isDirectory }
        val outDir = dirs.firstOrNull { it.resolve("data").isDirectory && it.resolve("img").isDirectory }
            ?: dirs.firstOrNull()
            ?: throw GradleException("$name：找不到合并后的 assets 输出目录（outputs 全是文件），开发期产物排除规则未生效")
        val base = outDir.toPath()
        // ① 模式是否与真实来源脱节 —— 查 src/main/assets，不查输出目录（理由见 devAssetSourceDir 注释）
        val srcBase = devAssetSourceDir.toPath()
        val srcHit = devAssetSourceDir.walkTopDown().filter { it.isFile }
            .filter { f ->
                val rel = srcBase.relativize(f.toPath()).toString().replace('\\', '/')
                devAssetRegexes.any { rx -> Pattern.matches(rx, rel) }
            }
            .toList()
        if (srcHit.isEmpty()) {
            throw GradleException(
                "$name：devAssetGlobs（${devAssetGlobs.joinToString()}）在 $devAssetSourceDir 下" +
                    "一个都没命中。模式已与真实文件脱节，排除规则等于失效——请核对实际路径。" +
                    "若这些开发期产物确已被清理，删掉 devAssetGlobs 里对应的条目，" +
                    "别让守卫靠「输出目录里本来就没有」这种自证来放行。"
            )
        }
        // ② 从输出里剔除。删不到是正常的（上次构建已删），不是错误。
        val hit = outDir.walkTopDown().filter { it.isFile }
            .filter { f ->
                val rel = base.relativize(f.toPath()).toString().replace('\\', '/')
                devAssetRegexes.any { rx -> Pattern.matches(rx, rel) }
            }
            .toList()
        var freed = 0L
        hit.forEach { freed += it.length(); it.delete() }
        // 顺手清掉剔除后空掉的目录，别让空目录条目进 ZIP（根目录本身保留）
        outDir.walkBottomUp().filter { it.isDirectory && it != outDir }.forEach { it.delete() }
        val leftover = outDir.walkTopDown()
            .filter { it.isFile && it.extension !in runtimeAssetExts }
            .toList()
        if (leftover.isNotEmpty()) {
            throw GradleException(
                "$name：剔除后 merged assets 里仍有非运行期格式的文件：" +
                    leftover.take(8).joinToString { base.relativize(it.toPath()).toString() } +
                    "。运行期只读 data/*.json、image_map.json、img/**，格式限 " +
                    "${runtimeAssetExts.joinToString()}；若确有运行期新格式，" +
                    "先把格式加进 runtimeAssetExts 并同步 verify 第 40 节，别让它静默漏进或漏掉。"
            )
        }
        logger.lifecycle(
            "[$name] 源目录命中 ${srcHit.size} 个开发期文件，本次从输出剔除 ${hit.size} 个（未压缩 ${freed} B）：${devAssetGlobs.joinToString()}"
        )
    }
}

// ── v2.51 D1：把 R8 mapping.txt 随每次 release 构建归档 ──────────────
// 用途：release 走 R8 混淆，崩溃栈里全是 `a.a` / `u1.t` 这类混淆名，没有 mapping 就永远
//       定位不到自己写的哪一行。这个 App 不上架、只有自己用，mapping 就是唯一的崩溃
//       溯源凭据——丢了只能回去翻源码猜。
//
// 产物：安装包归档/mapping/星露小助手_v<versionName>_c<versionCode>.mapping.txt.gz
//       文件名与归档 APK **同 stem**，只多一个 .mapping.txt.gz 后缀，
//       保证「哪个 APK 对应哪份 mapping」一眼可查、不会错配。
//
// 为什么压成 .gz：mapping.txt 原始 **31.3 MB**（3,666 个类，其中 androidx.compose 独占
//       60.8% 的字节），逐版原样存下来说一年就是 GB 级；gzip 后只有 **2.3 MB（7.2%）**，
//       解压回来与原文逐字节相同。用法：gzip -dc x.mapping.txt.gz | retrace < crash.txt
//
// 为什么用 Gradle task 而不是 tools/ 下的脚本：需求是「**每次构建**都自动归档」，
//       只有挂在构建图上的 task 才做得到——脚本要人记得敲，迟早漏版本。本文件本来就有
//       构建期后处理 doLast 的先例（上面剔除开发期 assets 那段）。
//
// ⚠ 安装包归档/mapping/ 必须写进 .gitignore：它不是 *.apk，不受既有忽略规则保护，
//    而 git 一旦把 2.3 MB 的二进制吞进历史就再也吐不出来。断言见 verify 第 44 节。

val archiveMapping = tasks.register("archiveMapping") {
    group = "build"
    description = "把 release 的 R8 mapping.txt 压成 .gz 归档到 安装包归档/mapping/（文件名与归档 APK 同 stem）"
    val srcFile = layout.buildDirectory.file("outputs/mapping/release/mapping.txt").get().asFile
    val destDir = rootProject.file("../安装包归档/mapping")
    val vn = android.defaultConfig.versionName
    val vc = android.defaultConfig.versionCode
    doLast {
        if (!srcFile.isFile) {
            throw GradleException(
                "archiveMapping：找不到 $srcFile。release 构建必须产出 mapping.txt；" +
                    "若确已关闭 R8（isMinifyEnabled = false），请一并删掉本任务与 verify 第 44 节，" +
                    "别让它退化成一条静默失效的规则。"
            )
        }
        destDir.mkdirs()
        val dest = File(destDir, "星露小助手_v${vn}_c${vc}.mapping.txt.gz")
        val raw = srcFile.length()
        FileOutputStream(dest).use { fos ->
            GZIPOutputStream(fos).use { gz -> srcFile.inputStream().use { it.copyTo(gz) } }
        }
        if (dest.length() >= raw) {
            throw GradleException(
                "archiveMapping：压完反而没变小（原始 $raw B -> ${dest.length()} B），gzip 没生效。"
            )
        }
        logger.lifecycle(
            "[archiveMapping] 已归档 ${dest.name}（原始 $raw B -> ${dest.length()} B，${dest.length() * 100 / raw}%）"
        )
    }
}

