// ⚠ v2.81.0：中文路径下的单元测试必须显式对齐编码，否则测试类**根本加载不了**。
//
// 现象：`gradlew :app:testDebugUnitTest` 报
//   ClassNotFoundException: com.stardew.assistant.data.WorldStateParserTest
// 而 `build/tmp/kotlin-classes/debugUnitTest/` 里明明有编译好的 .class。
//
// 根因：项目路径带中文（路径带中文），Gradle 把 classpath 交给
// 测试 worker 时会经过一次文本通道，**Gradle 侧按 UTF-8、worker 侧按平台默认
// （本机 GBK）**，路径在 worker 里变成乱码 → 找不到类。
// 这与源码里任何一处写法无关，是纯环境问题：机器一换、locale 一变就复现/消失。
//
// ⚠ 已试过 `systemProperty("file.encoding","UTF-8")` 与 `jvmArgs("-Dfile.encoding=UTF-8")`：
//   **都不管用**——worker 是在 JVM 起来之前就把 classpath 文本读进去的，
//   那时 file.encoding 还没生效。
// 所以真正能跑的是下面那个 `worldStateTest`（JavaExec 直起 JVM，classpath 走命令行宽字符通道）。
//
// 三条命令的关系：
//   gradlew :app:testDebugUnitTest   ← 标准做法，在 ASCII 路径 / CI 上可用
//   gradlew :app:worldStateTest       ← 本机（中文路径）能跑的那条，输出同样的结论
//   tools\run_world_state_test.ps1    ← 不依赖 Gradle 的兜底（把 jar 路径钉死）
tasks.withType<Test>().configureEach {
    systemProperty("file.encoding", "UTF-8")
    jvmArgs("-Dfile.encoding=UTF-8")
}

